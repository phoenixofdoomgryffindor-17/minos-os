void fb_init(MinOS_BootInfo *boot_info) {
    g_boot_info = boot_info;
    if (!boot_info || !boot_info->fb_base) return;
    g_fb = (uint32_t *)boot_info->fb_base;
    g_width = boot_info->fb_width;
    g_height = boot_info->fb_height;
    g_pitch_pixels = boot_info->fb_pitch / 4;
    g_is_bgr = boot_info->fb_is_bgr;
}

uint32_t fb_get_width(void)  { return g_width; }
uint32_t fb_get_height(void) { return g_height; }

static inline uint32_t convert_color(uint32_t argb) {
    /*
     * On little-endian x86_64, a 32-bit uint32 0xAARRGGBB is stored in memory as:
     *   byte 0: Blue  (0xBB)
     *   byte 1: Green (0xGG)
     *   byte 2: Red   (0xRR)
     *   byte 3: Alpha (0xAA)
     *
     * This matches PixelBlueGreenRedReserved8BitPerColor (BGRA) natively.
     * Only if the display format is PixelRedGreenBlueReserved8BitPerColor (RGBA)
     * do we need to swap the R and B channels.
     */
    if (!g_is_bgr) {
        uint32_t a = (argb >> 24) & 0xFF;
        uint32_t r = (argb >> 16) & 0xFF;
        uint32_t g = (argb >> 8)  & 0xFF;
        uint32_t b = argb & 0xFF;
        return (a << 24) | (b << 16) | (g << 8) | r;
    }
    return argb;
}

void fb_put_pixel(uint32_t x, uint32_t y, uint32_t argb) {
    if (!g_fb || x >= g_width || y >= g_height) return;
    g_fb[y * g_pitch_pixels + x] = convert_color(argb);
}

void fb_clear(uint32_t argb) {
    if (!g_fb) return;
    uint32_t c = convert_color(argb);
    for (uint32_t y = 0; y < g_height; y++) {
        uint32_t *row = &g_fb[y * g_pitch_pixels];
        for (uint32_t x = 0; x < g_width; x++) {
            row[x] = c;
        }
    }
}

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t argb) {
    if (!g_fb) return;
    if (x >= g_width || y >= g_height) return;
    if (x + w > g_width)  w = g_width - x;
    if (y + h > g_height) h = g_height - y;

    uint32_t c = convert_color(argb);
    for (uint32_t cy = y; cy < y + h; cy++) {
        uint32_t *row = &g_fb[cy * g_pitch_pixels + x];
        for (uint32_t cx = 0; cx < w; cx++) {
            row[cx] = c;
        }
    }
}

void fb_draw_rect_outline(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    if (!g_fb) return;
    /* Top and bottom */
    for (uint32_t i = 0; i < w; i++) {
        fb_put_pixel(x + i, y, color);
        fb_put_pixel(x + i, y + h - 1, color);
    }
    /* Left and right */
    for (uint32_t i = 0; i < h; i++) {
        fb_put_pixel(x, y + i, color);
        fb_put_pixel(x + w - 1, y + i, color);
    }
}

void fb_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = font_8x16_basic[(uint8_t)c - 32];

    for (int cy = 0; cy < 16; cy++) {
        uint8_t row = glyph[cy];
        for (int cx = 0; cx < 8; cx++) {
            if (row & (0x80 >> cx)) {
                fb_put_pixel(x + cx, y + cy, fg);
            } else if (bg != 0) {
                fb_put_pixel(x + cx, y + cy, bg);
            }
        }
    }
}

void fb_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg) {
    if (!str) return;
    uint32_t cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 18;
        } else {
            fb_draw_char(cx, y, *str, fg, bg);
            cx += 9;
        }
        str++;
    }
}

void fb_draw_badge(uint32_t x, uint32_t y, const char *text, uint32_t bg_color, uint32_t fg_color) {
    if (!text) return;
    int len = 0;
    while (text[len]) len++;
    uint32_t w = (uint32_t)(len * 9 + 16);
    uint32_t h = 24;

    fb_fill_rect(x, y, w, h, bg_color);
    fb_draw_rect_outline(x, y, w, h, COLOR_CARD_BORDER);
    fb_draw_string(x + 8, y + 4, text, fg_color, 0);
}
